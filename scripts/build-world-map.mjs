#!/usr/bin/env node
/**
 * Build the world outline bubble maps are drawn on (image-led visual systems,
 * item 5, 2026-10-13).
 *
 *   node scripts/build-world-map.mjs
 *
 * Reads `world-atlas` (a development dependency, ISC; the geometry is Natural
 * Earth's 1:110m land, which is public domain) and writes
 * `packages/renderer/src/world-map.ts`: every land ring as longitude and
 * latitude in tenths of a degree. The TopoJSON is decoded here, by hand: it is
 * a short algorithm, and a second package for it is a second thing to vendor.
 *
 * Land only, no borders: a bubble map's subject is the bubbles, and country
 * lines at slide size are noise that also date (borders change, coastlines
 * do not). The output is committed (the renderer runs offline and in the
 * headless exporter) and deterministic: the same world-atlas version writes
 * the same bytes.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const atlasDir = dirname(require.resolve("world-atlas/package.json"));
const topology = JSON.parse(readFileSync(join(atlasDir, "land-110m.json"), "utf8"));
const version = JSON.parse(readFileSync(join(atlasDir, "package.json"), "utf8")).version;

// TopoJSON arcs are quantized and delta-encoded; undo both.
const [scaleX, scaleY] = topology.transform.scale;
const [translateX, translateY] = topology.transform.translate;
const arcs = topology.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scaleX + translateX, y * scaleY + translateY];
  });
});

/** A ring from its arc indices; a negative index is that arc reversed (~index). */
function ring(indices) {
  const points = [];
  for (const index of indices) {
    const arc = index >= 0 ? arcs[index] : [...arcs[~index]].reverse();
    // Consecutive arcs share their joining point.
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  return points;
}

const rings = [];
const geometries = topology.objects.land.geometries ?? [topology.objects.land];
for (const geometry of geometries) {
  const polygons = geometry.type === "Polygon" ? [geometry.arcs] : geometry.type === "MultiPolygon" ? geometry.arcs : [];
  for (const polygon of polygons) for (const indices of polygon) rings.push(ring(indices));
}

/**
 * A ring that crosses the 180° meridian (Fiji, Chukotka, Wrangel Island) jumps
 * from +180 to -180 and back, and drawn as it stands it is a line across the
 * whole map. Such a ring crosses an even number of times; its longitudes are
 * made continuous here (running past 180), and the renderer draws it twice,
 * shifted by 360°, each copy clipped to the map. Antarctica crosses once: that
 * crossing is its own edge along the pole, and is left as it is.
 */
function unwrap(points) {
  let jumps = 0;
  for (let i = 1; i < points.length; i += 1) if (Math.abs(points[i][0] - points[i - 1][0]) > 180) jumps += 1;
  if (jumps === 0 || jumps % 2 === 1) return points;
  let shift = 0;
  return points.map(([lon, lat], i) => {
    if (i > 0) {
      const previous = points[i - 1][0];
      if (lon - previous > 180) shift -= 360;
      else if (previous - lon > 180) shift += 360;
    }
    return [lon + shift, lat];
  });
}

// Tenths of a degree is ~11km at the equator: far finer than a slide shows.
const encoded = rings
  .map(unwrap)
  .map((points) => {
    const out = [];
    for (const [lon, lat] of points) {
      const x = Math.round(lon * 10);
      const y = Math.round(lat * 10);
      if (out.length && out[out.length - 2] === x && out[out.length - 1] === y) continue;
      out.push(x, y);
    }
    return out;
  })
  // A ring of fewer than four distinct points is an islet nothing could see.
  .filter((flat) => flat.length >= 8);

const body = encoded.map((flat) => `  [${flat.join(",")}],`).join("\n");
const points = encoded.reduce((sum, flat) => sum + flat.length / 2, 0);

writeFileSync(
  join(root, "packages/renderer/src/world-map.ts"),
  `/**
 * GENERATED by scripts/build-world-map.mjs from world-atlas ${version} (land-110m).
 * Do not edit by hand; re-run the script.
 *
 * Natural Earth 1:110m land, public domain, redistributed by world-atlas
 * (ISC, Copyright 2013-2019 Michael Bostock). ${encoded.length} rings, ${points} points, each
 * ring a flat list of longitude and latitude in tenths of a degree. A ring
 * that crosses the 180° meridian runs past ±1800 rather than jumping.
 */
export const WORLD_LAND: readonly (readonly number[])[] = [
${body}
];
`,
);
console.log(`world-map: ${encoded.length} rings, ${points} points`);
